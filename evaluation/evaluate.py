"""
evaluation/evaluate.py — Main evaluation runner.

Usage:
  python evaluation/evaluate.py --partition dev    # during development
  python evaluation/evaluate.py --partition test   # ONCE ONLY after M3 gate

Security invariant:
  --partition test is LOCKED until the M3 gate flag is set.
  Attempting to run the test partition without the flag raises a hard error.
  This prevents accidental test-set leakage (R5 in the risk register).

Evaluation protocol:
  1. Load genuine and impostor pair lists (generated by generate_pairs.py).
  2. For each pair: run both images through the pipeline, extract templates, compare.
  3. Collect scores (genuine) and scores (impostor) separately.
  4. Report: FAR, FRR, EER, bootstrap CIs, timing. One results file per run.
  5. Results file is NEVER overwritten — filename includes a timestamp.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import time

import config
from evaluation.metrics import bootstrap_ci, compute_far_frr, find_eer
from src import (
    enhancement,
    minutiae_extraction,
    orientation,
    preprocessing,
    segmentation,
    template as tmpl,
)
from src.matching import match
from src.security import get_secure_logger

_logger = get_secure_logger(__name__)

EVAL_DIR = pathlib.Path(__file__).parent
PAIRS_DIR = EVAL_DIR / "pairs"
RESULTS_DIR = pathlib.Path(__file__).parent.parent / "reports" / "results"
RESULTS_DIR.mkdir(parents=True, exist_ok=True)

# M3 gate flag file — must be created manually by the reviewer after M3 sign-off
M3_GATE_FILE = EVAL_DIR / "M3_GATE_CLEARED"


def _process_image(image_path: str) -> tmpl.FingerprintTemplate | None:
    """Run the full pipeline on one image; return None on failure."""
    try:
        img = preprocessing.validate_and_load(image_path)
        norm = preprocessing.normalise(img)
        orient = orientation.estimate(norm)
        enhanced = enhancement.enhance(norm, orient)
        mask = segmentation.segment(enhanced)
        skeleton = segmentation.skeletonise(enhanced, mask)
        raw_m = minutiae_extraction.extract(skeleton, orient, mask)
        filtered = minutiae_extraction.remove_spurious(raw_m, skeleton)
        return tmpl.create("eval", filtered)
    except Exception as exc:
        _logger.warning("Pipeline failed for image: %s", exc)
        return None


def run_evaluation(partition: str) -> None:
    if partition == "test":
        if not M3_GATE_FILE.exists():
            raise RuntimeError(
                "TEST PARTITION IS LOCKED. Create the file "
                f"{M3_GATE_FILE} after M3 reviewer sign-off to unlock."
            )
        _logger.info("M3 gate cleared. Running FINAL test-set evaluation.")

    genuine_file = PAIRS_DIR / f"{partition}_genuine.json"
    impostor_file = PAIRS_DIR / f"{partition}_impostor.json"

    if not genuine_file.exists() or not impostor_file.exists():
        raise FileNotFoundError(
            f"Pair files not found for partition '{partition}'. "
            "Run generate_pairs.py first."
        )

    genuine_pairs: list[tuple[str, str]] = json.loads(genuine_file.read_text())
    impostor_pairs: list[tuple[str, str]] = json.loads(impostor_file.read_text())

    _logger.info("Evaluating partition=%s genuine=%d impostor=%d",
                 partition, len(genuine_pairs), len(impostor_pairs))

    genuine_scores: list[float] = []
    impostor_scores: list[float] = []
    failed = 0
    extraction_times: list[float] = []
    comparison_times: list[float] = []

    # Cache templates to avoid redundant multi-second image re-extractions (R6 in Risk Register)
    template_cache: dict[str, tmpl.FingerprintTemplate | None] = {}

    def _timed_process(path: str):
        if path in template_cache:
            return template_cache[path]
        t0 = time.perf_counter()
        t = _process_image(path)
        extraction_times.append((time.perf_counter() - t0) * 1000)
        template_cache[path] = t
        return t

    def _timed_match(t1, t2):
        t0 = time.perf_counter()
        r = match(t1, t2)
        comparison_times.append((time.perf_counter() - t0) * 1000)
        return r

    for path1, path2 in genuine_pairs:
        t1 = _timed_process(path1)
        t2 = _timed_process(path2)
        if t1 is None or t2 is None:
            failed += 1
            continue
        result = _timed_match(t1, t2)
        genuine_scores.append(result.score)

    for path1, path2 in impostor_pairs:
        t1 = _timed_process(path1)
        t2 = _timed_process(path2)
        if t1 is None or t2 is None:
            failed += 1
            continue
        result = _timed_match(t1, t2)
        impostor_scores.append(result.score)

    threshold = config.MATCH_SCORE_THRESHOLD
    far, frr = compute_far_frr(genuine_scores, impostor_scores, threshold)
    eer, eer_t = find_eer(genuine_scores, impostor_scores)
    far_lo, far_hi, frr_lo, frr_hi = bootstrap_ci(genuine_scores, impostor_scores, threshold)

    results = {
        "partition": partition,
        "threshold": threshold,
        "far": far,
        "frr": frr,
        "eer": eer,
        "eer_threshold": eer_t,
        "genuine_count": len(genuine_scores),
        "impostor_count": len(impostor_scores),
        "failed_extractions": failed,
        "far_ci_95": [far_lo, far_hi],
        "frr_ci_95": [frr_lo, frr_hi],
        "mean_extraction_ms": sum(extraction_times) / max(len(extraction_times), 1),
        "mean_comparison_ms": sum(comparison_times) / max(len(comparison_times), 1),
    }

    # Results file is timestamped and NEVER overwritten
    ts = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    out_file = RESULTS_DIR / f"{partition}_results_{ts}.json"
    out_file.write_text(json.dumps(results, indent=2))

    print(f"\n{'='*50}")
    print(f"  Evaluation Results — {partition.upper()} partition")
    print(f"{'='*50}")
    print(f"  Threshold      : {threshold:.4f}")
    print(f"  FAR            : {far:.4f}  95% CI [{far_lo:.4f}, {far_hi:.4f}]")
    print(f"  FRR            : {frr:.4f}  95% CI [{frr_lo:.4f}, {frr_hi:.4f}]")
    print(f"  EER            : {eer:.4f}  @ threshold={eer_t:.4f}")
    print(f"  Genuine pairs  : {len(genuine_scores)}")
    print(f"  Impostor pairs : {len(impostor_scores)}")
    print(f"  Failed extract : {failed}")
    print(f"  Avg extract    : {results['mean_extraction_ms']:.1f} ms")
    print(f"  Avg compare    : {results['mean_comparison_ms']:.1f} ms")
    print(f"{'='*50}")
    print(f"  Results saved to: {out_file.name}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Fingerprint biometric evaluation")
    parser.add_argument("--partition", choices=["dev", "test"], required=True)
    args = parser.parse_args()
    run_evaluation(args.partition)
